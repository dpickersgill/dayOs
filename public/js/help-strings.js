/** The text of key in lang, with {name} filled in from vars. Falls back to English. */
export function t(lang, key, vars) {
  const s = (STRINGS[lang] && STRINGS[lang][key]) || STRINGS.en[key] || key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m)) : s;
}

/** The language to show: the guest's own choice, else the server's reading of the phone's language, else English. */
export const pickLang = (chosen, server, phone) => [chosen, server, String(phone || '').slice(0, 2).toLowerCase()].find((l) => l === 'en' || l === 'es') || 'en';

/**
 * The text a guest sends when the page cannot reach patrol: "HELP <code or place> <lat>,<lng> ±<acc>m <what>".
 * The first word stays HELP in every language, so patrol's text line reads it the same way.
 */
export function smsBody({ code, place, lat, lng, acc, what }) {
  const parts = ['HELP'];
  const where = code || place;
  if (where) parts.push(String(where).replace(/\s+/g, ' ').trim().slice(0, 60));
  if (Number.isFinite(lat) && Number.isFinite(lng)) {
    parts.push(`${lat.toFixed(5)},${lng.toFixed(5)}`);
    if (Number.isFinite(acc)) parts.push(`±${Math.round(acc)}m`);
  }
  if (what) parts.push(String(what).replace(/\s+/g, ' ').trim().slice(0, 140));
  return parts.join(' ');
}

/** iPhone and iPad (also an iPad that says it is a Mac) open "sms:<n>&body=", Android "sms:<n>?body=". */
export const isApple = (ua, touchPoints) => /iPad|iPhone|iPod/.test(String(ua)) || (/Macintosh/.test(String(ua)) && Number(touchPoints) > 1);
export function smsHref(number, body, apple) {
  const n = String(number || '').replace(/[^0-9+]/g, '');
  return `sms:${n}${apple ? '&' : '?'}body=${encodeURIComponent(body)}`;
}
